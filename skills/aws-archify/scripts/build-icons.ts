// Generate src/icons from the AWS Architecture Icons package: one typed React component per icon (service.js,
// resource.js, group.js, category.js and their .d.ts), the factory they share (runtime.js), a barrel (index.js)
// and catalog.json, the metadata that find-icon and the editor search.
//
//   node scripts/build-icons.ts [<icons-dir>]        (npm run icons)
//
// The package folder is the argument, else $AWS_ICONS_DIR, else the nearest Icons/ folder above the renderer.
// Scenes import the components directly, so nothing reads the package at render time.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ICON_RUNTIME_JS, iconModuleLine } from "./lib/icon-catalog.ts";
import {
  PACKAGE_HELP, componentName, locateIconsDir, readSvgText, scanIconPackage, svgParts,
} from "./lib/icon-package.ts";

const RENDERER_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(RENDERER_ROOT, "src", "icons");
const MODULES = ["service", "resource", "group", "category"];

interface IconSource {
  exportName: string;
  viewBox: string;
  markup: string;
}

interface CatalogEntry {
  exportName: string;
  name: string;
  raw: string;
  type: string;
  category: string | null;
  size: number | null;
  color: string | null;
  path: string;
  module: string;
}

const NOTICE = "// AUTO-GENERATED by scripts/build-icons.ts from the AWS Architecture Icons package; do not edit.\n";

const MODULE_HEADER = NOTICE + [
  '// One component per official icon, its SVG markup unchanged. Use as <Node icon={Name} label="..." />.',
  'import { icon } from "./runtime.js";',
  "",
  "",
].join("\n");

const DECLARATIONS_HEADER = NOTICE + 'import type { IconComponent } from "../engine.tsx";\n\n';

const REEXPORTS = MODULES.map((m) => `export * from "./${m}.js";\n`).join("");

const INDEX_JS = NOTICE + REEXPORTS + 'import catalog from "./catalog.json" with { type: "json" };\n' +
  "export { catalog };\n";

const INDEX_DTS =
  NOTICE +
  REEXPORTS +
  "export declare const catalog: Array<{ exportName: string; name: string; raw: string; type: string; " +
  "category: string | null; size: number | null; color: string | null; path: string; module: string }>;\n";

const moduleJs = (icons: IconSource[]): string =>
  MODULE_HEADER + icons.map((i) => `${iconModuleLine(i.exportName, i.viewBox, i.markup)}\n`).join("");

const moduleDts = (icons: IconSource[]): string =>
  DECLARATIONS_HEADER + icons.map((i) => `export declare const ${i.exportName}: IconComponent;\n`).join("");

function fail(message: string): never {
  console.error(`error: ${message}\n${PACKAGE_HELP}`);
  process.exit(1);
}

// Two icons can share a name (the same service under two categories); later ones get _2, _3, ...
function claimName(base: string, taken: Set<string>): string {
  let name = base;
  for (let n = 2; taken.has(name); n++) name = `${base}_${n}`;
  taken.add(name);
  return name;
}

function main(): void {
  const dirArg = process.argv.slice(2).find((arg) => !arg.startsWith("-"));
  const located = locateIconsDir(dirArg, process.env.AWS_ICONS_DIR, RENDERER_ROOT);
  if ("problem" in located) fail(located.problem);
  const root = located.dir;
  const found = scanIconPackage(root);
  if (found.length === 0) fail(`no icon SVGs found under ${root}`);
  console.error(`Indexed ${found.length} SVG icons from ${root}`);

  const modules = new Map<string, IconSource[]>(MODULES.map((m) => [m, []]));
  const catalog: CatalogEntry[] = [];
  const taken = new Set<string>();
  for (const icon of found) {
    const list = modules.get(icon.type);
    if (!list) continue;
    const text = readSvgText(path.join(root, icon.path));
    if (text === null) {
      console.warn("skip (unreadable):", icon.path);
      continue;
    }
    const exportName = claimName(componentName(icon.name), taken);
    list.push({ exportName, ...svgParts(text) });
    catalog.push({
      exportName, name: icon.name, raw: icon.raw, type: icon.type, category: icon.category,
      size: icon.size, color: icon.color, path: icon.path, module: `./${icon.type}.js`,
    });
  }
  // Everything below overwrites src/icons, so stop while it is still intact.
  if (catalog.length === 0) {
    fail(`none of the ${found.length} indexed icons could be read from ${root}; src/icons left unchanged.`);
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, "runtime.js"), ICON_RUNTIME_JS);
  for (const [module, icons] of modules) {
    fs.writeFileSync(path.join(OUT_DIR, `${module}.js`), moduleJs(icons));
    fs.writeFileSync(path.join(OUT_DIR, `${module}.d.ts`), moduleDts(icons));
    console.log(`wrote src/icons/${module}.js + ${module}.d.ts (${icons.length} components)`);
  }
  fs.writeFileSync(path.join(OUT_DIR, "index.js"), INDEX_JS);
  fs.writeFileSync(path.join(OUT_DIR, "index.d.ts"), INDEX_DTS);
  fs.writeFileSync(path.join(OUT_DIR, "catalog.json"), JSON.stringify(catalog, null, 1));
  console.log(`wrote src/icons/index.js + index.d.ts + catalog.json (${catalog.length} icons total)`);
}

main();
